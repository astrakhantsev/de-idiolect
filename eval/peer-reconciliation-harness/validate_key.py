#!/usr/bin/env python3
"""Structural validation of a key (concepts.json). Prints STRUCTURE ONLY — never
descriptions — so a sealed key can be validated without the orchestrator reading it.
Also emits answer_key.json alongside. Usage: validate_key.py <workspace>/key/concepts.json"""
import json, sys, re

path = sys.argv[1]
k = json.load(open(path))
pairs = k["pairs"]
errs = []
if len(pairs) != 10: errs.append(f"expected 10 pairs, got {len(pairs)}")
expect = {"P01": "exactMatch", "P02": "exactMatch", "P03": "broadnarrow", "P04": "broadnarrow",
          "P05": "relatedMatch", "P06": "relatedMatch", "P07": "noMatchDespiteSimilarity",
          "P08": "noMatchDespiteSimilarity", "P09": "noMatch", "P10": "noMatch"}
terms_a, terms_b = {}, {}
for p in pairs:
    pid = p.get("pair_id"); cls = p.get("class")
    if expect.get(pid) != cls: errs.append(f"{pid}: class {cls} != expected {expect.get(pid)}")
    if cls == "broadnarrow" and p.get("broader_side") not in ("a", "b"): errs.append(f"{pid}: missing broader_side")
    if cls == "relatedMatch" and not p.get("core"): errs.append(f"{pid}: missing core")
    for s in ("a", "b"):
        t = p.get(s, {}).get("term", ""); d = p.get(s, {}).get("desc", "")
        if not t: errs.append(f"{pid}.{s}: missing term")
        if len(d.split()) < 25: errs.append(f"{pid}.{s}: desc too short ({len(d.split())}w)")
        (terms_a if s == "a" else terms_b)[t] = pid
    if cls == "noMatchDespiteSimilarity" and p["a"]["term"] != p["b"]["term"]: errs.append(f"{pid}: jingle terms differ")
    if cls != "noMatchDespiteSimilarity" and p["a"]["term"].lower() == p["b"]["term"].lower(): errs.append(f"{pid}: non-jingle identical terms")
jingles = {p["a"]["term"] for p in pairs if p["class"] == "noMatchDespiteSimilarity"}
for ta in terms_a:
    for tb in terms_b:
        if ta.lower() == tb.lower() and ta not in jingles: errs.append(f"cross-side collision: {ta}")
for p in pairs:
    for s in ("a", "b"):
        d = p[s]["desc"].lower()
        for t, owner in list(terms_a.items()) + list(terms_b.items()):
            if owner != p["pair_id"] and re.search(re.escape(t.lower()), d):
                errs.append(f"{p['pair_id']}.{s} desc contains other pair's term '{t}'")
        for meta in ("match", "broader", "narrower", "residue", "planted", "jingle", "community"):
            if re.search(rf"\b{meta}\b", d): errs.append(f"{p['pair_id']}.{s} desc contains meta word '{meta}'")

print("STRUCTURE:", " ".join(f"{p['pair_id']}={p['class']}{'('+p.get('broader_side','')+')' if p['class']=='broadnarrow' else ''}" for p in pairs))
print("TERMS a:", sorted(terms_a)); print("TERMS b:", sorted(terms_b))
if errs:
    print("INVALID:"); [print(" -", e) for e in errs]; sys.exit(1)
ak = {"note": "generated by validate_key.py", "pairs": [
    {"pair_id": p["pair_id"], "term_a": p["a"]["term"], "term_b": p["b"]["term"], "expected": p["class"],
     **({"broader_side": p["broader_side"]} if p["class"] == "broadnarrow" else {})} for p in pairs]}
json.dump(ak, open(path.replace("concepts.json", "answer_key.json"), "w"), indent=1)
print("VALID; answer_key.json written")
